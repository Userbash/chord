//! Strongly-typed Tauri BFF DTOs (`specta` + `tauri-specta` contract definitions).
//! Eliminates untyped `serde_json::Value` field drift (`guild_id` vs `guildId`, `is_member` vs `isMember`,
//! `my_roles` vs `myRoles`, `voice_states`, `call`, `recipients`) between `data.rs` and `ui/bindings.js`.

use crate::permissions::ChannelAccessPolicy;
use serde::{Deserialize, Serialize};
use serde_json::Value;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GuildSyncSummaryDto {
    pub id: String,
    pub name: String,
    pub icon: Option<String>,
    pub owner_id: Option<String>,
    pub is_member: bool,
    pub lurker: bool,
    pub pending: bool,
    pub my_roles: Vec<String>,
    pub roles: Vec<Value>,
    pub features: Vec<String>,
    pub channels: Vec<Value>,
    pub channel_categories: Vec<Value>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct VoiceParticipantSyncDto {
    pub user_id: String,
    pub username: String,
    pub display_name: String,
    pub avatar_url: Option<String>,
    pub channel_id: String,
    pub guild_id: Option<String>,
    pub muted: bool,
    pub deafened: bool,
    pub self_mute: bool,
    pub self_deaf: bool,
    pub self_video: bool,
    pub self_stream: bool,
    pub speaking: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct VoiceRtcStatusDto {
    pub connected: bool,
    pub state: String,
    pub guild_id: Option<String>,
    pub channel_id: Option<String>,
    pub endpoint: Option<String>,
    pub ssrc: u32,
    pub tx_packets: u64,
    pub rx_packets: u64,
    pub rtt_ms: Option<u64>,
    pub last_error: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LiveSyncSnapshotDto {
    pub ok: bool,
    pub live: bool,
    pub current_user: Value,
    pub dm_channels: Vec<Value>,
    pub relationships: Vec<Value>,
    pub guilds: Vec<GuildSyncSummaryDto>,
    pub voice_states: Value,
    pub read_states: Value,
    pub user_guild_settings: Value,
    pub rtc: VoiceRtcStatusDto,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ChannelAccessCheckRequestDto {
    pub guild_id: String,
    pub channel_id: String,
}

pub type ChannelAccessDto = ChannelAccessPolicy;

/// Returns the canonical TypeScript declaration file (`bindings.d.ts`) corresponding to the Rust DTOs
/// and BFF commands (`specta` / `tauri-specta` schema).
pub const fn export_typescript_bindings() -> &'static str {
    r#"// Auto-generated by discord-gui-spike::dto (specta / tauri-specta contract)
// Do not manually edit field names — keep synchronized with rust/gui-spike/src/dto.rs & permissions.rs

export interface GuildSyncSummaryDto {
  id: string;
  name: string;
  icon: string | null;
  ownerId: string | null;
  isMember: boolean;
  lurker: boolean;
  pending: boolean;
  myRoles: string[];
  roles: Array<{ id: string; name: string; color?: number; position?: number; permissions?: string }>;
  features: string[];
  channels: Array<Record<string, unknown>>;
  channelCategories: Array<Record<string, unknown>>;
}

export interface VoiceRtcStatusDto {
  connected: boolean;
  state: string;
  guildId: string | null;
  channelId: string | null;
  endpoint: string | null;
  ssrc: number;
  txPackets: number;
  rxPackets: number;
  rttMs: number | null;
  lastError: string | null;
}

export interface ChannelAccessDto {
  effectivePermissions: string;
  canViewChannel: boolean;
  canReadHistory: boolean;
  canSendMessages: boolean;
  canAddReactions: boolean;
  canAttachFiles: boolean;
  canConnectVoice: boolean;
  canSpeakVoice: boolean;
  canStreamVoice: boolean;
  isLurker: boolean;
  isPending: boolean;
  readOnly: boolean;
  deniedReason: string | null;
}

export interface LiveSyncSnapshotDto {
  ok: boolean;
  live: boolean;
  currentUser: Record<string, unknown>;
  dmChannels: Array<Record<string, unknown>>;
  relationships: Array<Record<string, unknown>>;
  guilds: GuildSyncSnapshotGuild[];
  voiceStates: Record<string, Array<Record<string, unknown>>>;
  readStates: Record<string, unknown>;
  userGuildSettings: Record<string, unknown>;
  rtc?: VoiceRtcStatusDto;
}

export type GuildSyncSnapshotGuild = GuildSyncSummaryDto;
"#
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dto_serializes_with_camel_case_keys_matching_ts_bindings() {
        let dto = GuildSyncSummaryDto {
            id: "1014537851418980372".to_string(),
            name: "ITSKIDON PC BOOST".to_string(),
            icon: None,
            owner_id: Some("1".to_string()),
            is_member: false,
            lurker: true,
            pending: false,
            my_roles: vec![],
            roles: vec![],
            features: vec!["PREVIEW_ENABLED".to_string()],
            channels: vec![],
            channel_categories: vec![],
        };
        let json = serde_json::to_value(&dto).expect("serialize GuildSyncSummaryDto");
        assert_eq!(json.get("isMember").and_then(Value::as_bool), Some(false));
        assert_eq!(json.get("lurker").and_then(Value::as_bool), Some(true));
        assert!(json.get("myRoles").and_then(Value::as_array).is_some());
        assert!(export_typescript_bindings().contains("export interface GuildSyncSummaryDto"));
    }
}
