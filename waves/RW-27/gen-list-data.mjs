#!/usr/bin/env node
// Генератор данных и независимого оракула для `Intl.ListFormat` (P7-01b, RW-27).
//
// Источник истины — ICU, доступный через Node 24 (`Intl.ListFormat`). Скрипт
// офлайн-детерминированный: фиксированный набор локалей/стилей/типов/элементов.
//
// Выход:
//   waves/RW-27/generated/list_data.rs      — таблица для продукта (после red)
//   waves/RW-27/fixtures/list-oracle.json   — ожидаемые строки для тестов
//
// Запуск: node waves/RW-27/gen-list-data.mjs

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");

const LOCALES = [
  "en-US", "en-GB", "zh-CN", "zh-TW", "cs", "da", "nl", "fr", "de", "el", "hu",
  "it", "ja", "ko", "pl", "ru", "pt-BR", "es-419", "es-ES", "sv-SE", "tr", "bg", "uk",
  "fi", "no", "hr", "ro", "lt", "th", "vi", "hi",
];
const STYLES = ["long", "short", "narrow"];
const TYPES = ["conjunction", "disjunction", "unit"];
const SAMPLES = ["A", "B", "C", "D", "E"];

function patternsFor(locale, style, type) {
  const formatter = new Intl.ListFormat(locale, { style, type });
  const literals = (items) =>
    formatter
      .formatToParts(items)
      .filter((part) => part.type === "literal")
      .map((part) => part.value);

  const pair = literals(["A", "B"]).join("");
  // 3 элемента дают [start, end], 5 элементов — [start, middle, middle, end].
  const three = literals(["A", "B", "C"]);
  const five = literals(["A", "B", "C", "D", "E"]);
  const start = three[0] ?? "";
  const end = three[1] ?? three[0] ?? "";
  const middle = five.length >= 3 ? five[1] : start;
  return { pair, start, middle, end };
}

function escapeRust(value) {
  return JSON.stringify(value);
}

function render(pattern, items) {
  if (items.length === 0) return "";
  if (items.length === 1) return items[0];
  if (items.length === 2) return `${items[0]}${pattern.pair}${items[1]}`;
  let out = `${items[0]}${pattern.start}${items[1]}`;
  for (let index = 2; index < items.length - 1; index += 1) {
    out += `${pattern.middle}${items[index]}`;
  }
  return `${out}${pattern.end}${items[items.length - 1]}`;
}

const rows = [];
const oracle = [];
for (const locale of LOCALES) {
  for (const style of STYLES) {
    for (const type of TYPES) {
      const pattern = patternsFor(locale, style, type);
      rows.push({ locale, style, type, ...pattern });
      const formatter = new Intl.ListFormat(locale, { style, type });
      for (let count = 0; count <= SAMPLES.length; count += 1) {
        const items = SAMPLES.slice(0, count);
        const expected = formatter.format(items);
        const actual = render(pattern, items);
        if (actual !== expected) {
          throw new Error(
            `${locale}/${style}/${type}/${count}: ${JSON.stringify(actual)} != ${JSON.stringify(expected)}`,
          );
        }
        oracle.push({ locale, style, type, items, expected });
      }
    }
  }
}

const generated = `//! Generated by \`waves/RW-27/gen-list-data.mjs\` (Node 24 / ICU).
//! Do not edit by hand. Source of truth: \`Intl.ListFormat.formatToParts\`.
//!
//! Table layout: (locale, style, type, pair, start, middle, end).

#[derive(Clone, Copy, Debug)]
pub(crate) struct ListPatterns {
    pub pair: &'static str,
    pub start: &'static str,
    pub middle: &'static str,
    pub end: &'static str,
}

#[rustfmt::skip]
pub(crate) static LIST_PATTERNS: &[(&str, &str, &str, ListPatterns)] = &[
${rows
  .map(
    (row) =>
      `    (${escapeRust(row.locale)}, ${escapeRust(row.style)}, ${escapeRust(row.type)}, ListPatterns { pair: ${escapeRust(row.pair)}, start: ${escapeRust(row.start)}, middle: ${escapeRust(row.middle)}, end: ${escapeRust(row.end)} }),`,
  )
  .join("\n")}
];
`;

mkdirSync(resolve(here, "generated"), { recursive: true });
mkdirSync(resolve(here, "fixtures"), { recursive: true });
writeFileSync(resolve(here, "generated/list_data.rs"), generated);
writeFileSync(
  resolve(here, "fixtures/list-oracle.json"),
  `${JSON.stringify({ source: "Node 24 Intl.ListFormat", locales: LOCALES, cases: oracle }, null, 1)}\n`,
);

console.log(`rows=${rows.length} cases=${oracle.length}`);
