#!/usr/bin/env node
// @ts-check
/**
 * scripts/scaffold-dto.mjs — Zero-Token Rust/TS DTO Generator
 *
 * Автоматически генерирует типизированную Rust структуру DTO с атрибутами
 * serde(rename_all = "camelCase"), Clone, Debug, Serialize, Deserialize
 * и соответствующий TypeScript интерфейс.
 *
 * Полностью исключает трату токенов ИИ на банальную выписку структур данных.
 *
 * Использование:
 *   node scripts/scaffold-dto.mjs <StructName> "field1:string, field2:number?, field3:bool" [--out <path>]
 *   node scripts/scaffold-dto.mjs UserStatusDto "userId:string, status:string, customStatus:string?, isMobile:bool"
 */

import { writeFileSync, appendFileSync, existsSync } from 'node:fs';

const args = process.argv.slice(2);
if (args.length < 2) {
  console.log(`Использование: node scripts/scaffold-dto.mjs <StructName> "<fields>" [--out <file>]`);
  console.log(`Пример: node scripts/scaffold-dto.mjs UserStatusDto "userId:string, status:string, customStatus:string?, isMobile:bool"`);
  process.exit(1);
}

const structName = args[0] || 'MyDto';
const fieldsRaw = args[1] || '';

let outFile = null;
const outIdx = args.indexOf('--out');
if (outIdx !== -1 && args[outIdx + 1]) {
  outFile = args[outIdx + 1];
}

/**
 * @param {string} rawType
 * @param {boolean} isOptional
 * @returns {{ rustType: string, tsType: string }}
 */
function mapType(rawType, isOptional) {
  const t = rawType.trim().toLowerCase();
  let rustType = 'String';
  let tsType = 'string';

  if (t === 'string' || t === 'str') {
    rustType = 'String';
    tsType = 'string';
  } else if (t === 'number' || t === 'i64' || t === 'u64' || t === 'int') {
    rustType = 'u64';
    tsType = 'number';
  } else if (t === 'f64' || t === 'float') {
    rustType = 'f64';
    tsType = 'number';
  } else if (t === 'bool' || t === 'boolean') {
    rustType = 'bool';
    tsType = 'boolean';
  } else {
    // Пользовательский тип
    rustType = rawType.trim();
    tsType = rawType.trim();
  }

  if (isOptional) {
    rustType = `Option<${rustType}>`;
    tsType = `${tsType} | null`;
  }

  return { rustType, tsType };
}

const parsedFields = fieldsRaw
  .split(',')
  .map(f => f.trim())
  .filter(Boolean)
  .map(f => {
    const parts = f.split(':');
    let name = (parts[0] || '').trim();
    let typePart = parts[1] ? parts[1].trim() : 'string';
    let isOptional = false;

    if (name.endsWith('?')) {
      name = name.slice(0, -1);
      isOptional = true;
    }
    if (typePart.endsWith('?')) {
      typePart = typePart.slice(0, -1);
      isOptional = true;
    }

    // Rust snake_case name
    const snakeName = name.replace(/([A-Z])/g, '_$1').toLowerCase().replace(/^_/, '');
    const { rustType, tsType } = mapType(typePart, isOptional);

    return { name, snakeName, rustType, tsType, isOptional };
  });

// 1. Rust код
let rustCode = `/// Typed DTO \`${structName}\` generated by Zero-Token Scaffold.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ${structName} {
`;

for (const f of parsedFields) {
  if (f.isOptional) {
    rustCode += `    #[serde(default, skip_serializing_if = "Option::is_none")]\n`;
  }
  rustCode += `    pub ${f.snakeName}: ${f.rustType},\n`;
}
rustCode += `}\n`;

// 2. TypeScript определение
let tsCode = `export interface ${structName} {\n`;
for (const f of parsedFields) {
  tsCode += `  ${f.name}${f.isOptional ? '?' : ''}: ${f.tsType};\n`;
}
tsCode += `}\n`;

console.log('🦀 [RUST DTO]:\n' + rustCode);
console.log('📘 [TYPESCRIPT DTO]:\n' + tsCode);

if (outFile) {
  appendFileSync(outFile, '\n' + rustCode, 'utf8');
  console.log(`✅ Добавлено в ${outFile}`);
}
